CREATE TABLE SAL_MOD(
 EMPNO NUMBER(10), DNAME VARCHAR2(30), OLD_SAL NUMBER(10,2),
 MOD_DATE DATE, MODIFIER VARCHAR2(128)
 );
CREATE OR REPLACE TRIGGER TRG_SAL_MOD
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
BEGIN
 IF NVL(:OLD.SAL,-1)<>NVL(:NEW.SAL,-1) THEN
  INSERT INTO SAL_MOD(EMPNO,DNAME,OLD_SAL,MOD_DATE,MODIFIER)
  SELECT :OLD.EMPNO,DNAME,:OLD.SAL,SYSDATE,
         SYS_CONTEXT('USERENV','SESSION_USER')
  FROM DEPT WHERE DNO=:OLD.DEPTNO;
 END IF;
 END;
